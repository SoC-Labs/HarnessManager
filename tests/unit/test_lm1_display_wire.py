"""The lcd_mirror wire as Harness Manager reads it (docs/design/LCD_MIRROR.md §6.1; lane LM1).

The authority is the board's own bytes: ``tests/fixtures/lcdmirror_wire/`` (the Linux
lead's wire vectors, platform ``feat/lcd-mirror`` d86ce81, generated by the encoders
``mps3-lcdmirror`` sends with). Every vector is parsed and checked against the board's
``manifest.json`` (CRC-32s of the SOURCE pixels, so the decoder is judged on the picture),
and HM's encoder must rebuild each one byte for byte (the fake board speaks the board's
exact bytes). Hand-built payloads remain only as negative twins (a plausible misreading
must NOT give the picture). A corrupted vector must fail the checksum or the parse.
"""

from __future__ import annotations

import hashlib
import json
import os
import random
import struct
import zlib
from pathlib import Path
from typing import Any

import pytest

from harness_manager.core import display as D
from harness_manager.core import display_wire as w

VECTORS = Path(__file__).resolve().parents[1] / "fixtures" / "lcdmirror_wire"
MANIFEST = json.loads((VECTORS / "manifest.json").read_text())
ENTRIES = {e["file"]: e for e in MANIFEST["vectors"]}
UPDATES = [e for e in MANIFEST["vectors"] if e["kind"] == "update"]
KEYFRAME = next(e for e in MANIFEST["vectors"] if e["kind"] == "keyframe")
REFUSALS = [e["file"] for e in MANIFEST["vectors"] if e["kind"] == "refusal"]
TEXT_ONLY_SW = w.ST_RST_N | w.ST_BL | w.ST_DISPLAY_ON | w.ST_FMT_OK | w.S_TEXT_ONLY


def vector(name: str) -> bytes:
    return (VECTORS / name).read_bytes()


def sha256sums() -> dict[str, str]:
    out = {}
    for line in (VECTORS / "SHA256SUMS").read_text().splitlines():
        digest, name = line.split()
        out[name] = digest
    return out


def read_one(data: bytes, max_msg: int = w.MAX_MSG_DEFAULT) -> Any:
    got = w.MessageReader(max_msg).feed(data)
    assert len(got) == 1
    return got[0]


