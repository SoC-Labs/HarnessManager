def keyframe_parts() -> list[bytes]:
    return [vector(p) for p in KEYFRAME["parts"]]


def test_split_keyframe_vector_is_the_frame() -> None:
    reader = w.MessageReader()
    ups = [m for part in keyframe_parts() for m in reader.feed(part)]
    assert [u.seq for u in ups] == [KEYFRAME["seq_first"] + i for i in range(3)]
    assert [(u.key, u.key_first, u.key_last, u.snap_last) for u in ups] == [
        (True, True, False, False), (True, False, False, False), (True, False, True, True)]
    assert ups[0].regs is not None and ups[1].regs is None and ups[1].mode == 0x00090520
    assert len({(u.t_ms, u.frames, u.resets, u.status & ~w.S_FRAMING, u.valid) for u in ups}) == 1
    assert all(len(p) <= 65536 for p in keyframe_parts())         # max_msg counts the header
    f = D.DisplayFrame()
    f.commit(ups, D.decode_parts(ups), key=True)
    assert 300 - f.hatched() == KEYFRAME["valid_count"]
    assert zlib.crc32(f.rgb565()) == KEYFRAME["frame_crc"]
    assert sum(len(u.tiles) for u in ups) == 300 and {r.enc for u in ups for r in u.tiles} == {w.E_RAW}


def test_hm_splits_the_keyframe_exactly_as_the_board_does() -> None:
    reader = w.MessageReader()
    ups = [m for part in keyframe_parts() for m in reader.feed(part)]
    f = D.DisplayFrame()
    f.commit(ups, D.decode_parts(ups), key=True)
    recs = w.encode_records(f.rgb565(), range(300))
    parts = w.split_records(recs, w.part_budget(w.MAX_MSG_DEFAULT, True))
    first = ups[0]
    rebuilt = []
    for i, chunk in enumerate(parts):
        flags = w.S_KEY | (w.S_KEY_FIRST if i == 0 else 0) | \
            ((w.S_KEY_LAST | w.S_SNAP_LAST) if i == len(parts) - 1 else 0)
        rebuilt.append(w.update_msg(first.seq + i, first.t_ms, first.frames, first.resets,
                                    (first.status & ~w.S_FRAMING) | flags, first.owner, first.valid,
                                    chunk, regs=first.regs, mode=ups[1].mode))
    assert rebuilt == keyframe_parts()


