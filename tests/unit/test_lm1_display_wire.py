# --- negative twin: a corrupted vector must fail the checksum or the parse -----------------------


def _judge(name: str, data: bytes) -> str:
    """'ok' when ``data`` still decodes to what the manifest says; else why not."""
    if hashlib.sha256(data).hexdigest() != sha256sums()[name]:
        checksum = "checksum"
    else:
        checksum = ""
    try:
        if name.startswith("key_split_"):
            parts = [data if p == name else vector(p) for p in KEYFRAME["parts"]]
            reader = w.MessageReader()
            ups = [m for part in parts for m in reader.feed(part)]
            f = D.DisplayFrame()
            f.commit(ups, D.decode_parts(ups), key=True)
            good = zlib.crc32(f.rgb565()) == KEYFRAME["frame_crc"] and \
                [u.seq for u in ups] == [KEYFRAME["seq_first"] + i for i in range(3)]
        elif name.startswith("update_"):
            e = ENTRIES[name]
            u = read_one(data)
            ((idx, enc, ln, crc),) = e["tiles"]
            (rec,) = u.tiles
            good = (u.seq, u.t_ms, u.status, u.owner) == (e["seq"], e["t_ms"], e["status"], e["owner"]) \
                and (rec.idx, rec.enc, len(rec.payload)) == (idx, enc, ln) \
                and zlib.crc32(w.decode_tile(rec.enc, rec.payload)) == crc \
                and w.valid_tiles(u.valid) == set(range(300))
        elif name == "hello.bin":
            info = read_one(data)
            good = info == read_one(vector("hello.bin"))
        else:
            ref = read_one(data)
            good = ref == read_one(vector(name))
    except (w.WireError, ValueError, struct.error, AssertionError):
        return "parse" + (f"+{checksum}" if checksum else "")
    if not good:
        return "manifest" + (f"+{checksum}" if checksum else "")
    return checksum or "ok"


CORRUPTIONS = [(name, spot) for name in sorted(sha256sums()) if name != "manifest.json"
               for spot in ("magic", "length", "middle", "last")]


@pytest.mark.parametrize("name, spot", CORRUPTIONS, ids=[f"{n}-{s}" for n, s in CORRUPTIONS])
def test_negative_twin_a_corrupted_vector_is_caught(name: str, spot: str) -> None:
    data = bytearray(vector(name))
    assert _judge(name, bytes(data)) == "ok"                      # the twin's control
    i = {"magic": 0, "length": 4, "middle": len(data) // 2, "last": len(data) - 2}[spot]
    data[i] ^= 0x5A
    assert _judge(name, bytes(data)) in ("parse+checksum", "manifest+checksum")


def test_negative_twin_a_one_bit_pixel_flip_passes_the_parse_but_not_the_manifest() -> None:
    """The subtle case: a flipped pixel bit is a well-formed message. Only the manifest's
    CRC of the source pixels catches it, which is why the vectors carry it."""
    data = bytearray(vector("update_raw.bin"))
    data[-1] ^= 0x01
    u = read_one(bytes(data))                                    # parses cleanly
    assert _judge("update_raw.bin", bytes(data)) == "manifest+checksum"
    assert zlib.crc32(w.decode_tile(u.tiles[0].enc, u.tiles[0].payload)) != ENTRIES["update_raw.bin"]["tiles"][0][3]


